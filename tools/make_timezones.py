#!/usr/bin/env python3
"""Generates Desk_Watch_CYD_V1/TimeZones.h: every country and city of the IANA tz database
with its POSIX TZ rule, English and French country names, as one compact JSON string in flash.
Needs: pip install pycountry tzdata  (and /usr/share/zoneinfo)."""
import gettext, json, os, sys
from pathlib import Path
import pycountry

root = Path(__file__).resolve().parent.parent
ZI = Path('/usr/share/zoneinfo')

def posix_rule(name):
    data = (ZI / name).read_bytes()
    foot = data.rstrip(b'\n').split(b'\n')[-1].decode()
    return foot

fr = gettext.translation('iso3166-1', pycountry.LOCALES_DIR, languages=['fr'], fallback=True)
countries = {}
for line in (ZI / 'zone.tab').read_text(encoding='utf8').splitlines():
    if line.startswith('#') or not line.strip():
        continue
    cc, _coords, tz, *_ = line.split('\t')
    countries.setdefault(cc, []).append(tz)

EXTRA = {'VN': ['Asia/Ho_Chi_Minh:Hanoi']}          # popular cities that share a zone with another city
EN_NAMES = {'VN': 'Vietnam', 'KR': 'South Korea', 'KP': 'North Korea', 'RU': 'Russia', 'TW': 'Taiwan', 'IR': 'Iran',
            'SY': 'Syria', 'TZ': 'Tanzania', 'BO': 'Bolivia', 'VE': 'Venezuela', 'MD': 'Moldova', 'LA': 'Laos',
            'CZ': 'Czechia', 'PS': 'Palestine', 'FM': 'Micronesia', 'BN': 'Brunei', 'CD': 'DR Congo', 'CG': 'Congo',
            'TR': 'Turkey', 'MK': 'North Macedonia', 'CI': "Cote d'Ivoire", 'FK': 'Falkland Islands'}
FR_NAMES = {'VN': 'Vietnam', 'KR': 'Corée du Sud', 'KP': 'Corée du Nord', 'RU': 'Russie', 'TW': 'Taïwan', 'IR': 'Iran',
            'SY': 'Syrie', 'TZ': 'Tanzanie', 'BO': 'Bolivie', 'VE': 'Venezuela', 'MD': 'Moldavie', 'LA': 'Laos',
            'CZ': 'Tchéquie', 'PS': 'Palestine', 'FM': 'Micronésie', 'BN': 'Brunei', 'CD': 'RD Congo', 'CG': 'Congo',
            'TR': 'Turquie', 'MK': 'Macédoine du Nord', 'CI': "Côte d'Ivoire", 'FK': 'Îles Malouines'}

def city_of(tz):
    return tz.split('/', 1)[1].replace('_', ' ') if '/' in tz else tz

rules, rule_index = [], {}
def rule_id(r):
    if r not in rule_index:
        rule_index[r] = len(rules); rules.append(r)
    return rule_index[r]

out = []
for cc in countries:
    c = pycountry.countries.get(alpha_2=cc)
    en = EN_NAMES.get(cc) or getattr(c, 'common_name', None) or c.name
    frn = FR_NAMES.get(cc) or fr.gettext(c.name)
    cities = []
    for tz in countries[cc]:
        cities.append([city_of(tz).split('/')[-1], rule_id(posix_rule(tz)), tz])
    for extra in EXTRA.get(cc, []):
        tz, label = extra.split(':')
        cities.append([label, rule_id(posix_rule(tz)), tz])
    cities.sort(key=lambda x: x[0])
    out.append([cc, en, frn, cities])
out.sort(key=lambda x: x[1])

# IANA aliases (links) so the browser's own zone name can be matched
links = {}
zi = ZI / 'tzdata.zi'
if zi.exists():
    for line in zi.read_text().splitlines():
        if line.startswith('L '):
            _, target, alias = line.split()
            links[alias] = target
all_zones = {tz for tzs in countries.values() for tz in tzs}
alias = {a: t for a, t in links.items() if t in all_zones and '/' in a}

data = {'r': rules,
        'c': [[cc, en, frn, [[city, rid] for city, rid, _tz in cities]] for cc, en, frn, cities in out],
        'z': {tz: [cc, city] for cc, _en, _fr, cities in out for city, _rid, tz in cities if True for cc in [cc]},
        'a': alias}
# 'z' maps an IANA name to [country code, city] for the browser auto-detection
js = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
print('countries', len(out), 'rules', len(rules), 'json bytes', len(js.encode('utf8')), file=sys.stderr)
(root / 'tools' / 'timezones.json').write_text(js, encoding='utf8')

import gzip
raw = js.encode('utf8')
gz = gzip.compress(raw, 9, mtime=0)
lines = []
for i in range(0, len(gz), 20):
    lines.append('  ' + ', '.join('0x%02X' % b for b in gz[i:i + 20]) + ',')
header = ('// Generated by tools/make_timezones.py - do not edit. IANA tz database: countries, cities, POSIX rules (gzip-compressed JSON).\n'
          '#pragma once\n#include <Arduino.h>\n'
          'inline constexpr size_t TZ_JSON_GZ_LEN = %d;\n'
          'static const uint8_t TZ_JSON_GZ[TZ_JSON_GZ_LEN] PROGMEM = {\n%s\n};\n' % (len(gz), '\n'.join(lines)))
(root / 'Desk_Watch_CYD_V1' / 'TimeZones.h').write_text(header, encoding='utf8')
print('gzip bytes', len(gz), file=sys.stderr)
