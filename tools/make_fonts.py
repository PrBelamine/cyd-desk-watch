#!/usr/bin/env python3
"""Generate the two embedded TFT_eSPI smooth fonts (VLW) used by Desk Watch CYD.

  Font15.h : DejaVu Sans Bold 15 px, Latin-1 + Latin Extended-A + typographic marks (labels, tasks)
  Font60.h : DejaVu Sans Bold 60 px, digits and  : . - space only (clock, timer, counter)

Usage: python3 tools/make_fonts.py [path/to/DejaVuSans-Bold.ttf]   (needs Pillow)
DejaVu Sans is free to use and redistribute (Bitstream Vera licence, see THIRD_PARTY_NOTICES.txt).
"""
import struct, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'
OUT = Path(__file__).resolve().parent.parent / 'Desk_Watch_CYD_V1'

LATIN = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
         [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC])
DIGITS = [ord(c) for c in ' 0123456789:.-']

def build(size, codes, symbol, filename):
    font = ImageFont.truetype(TTF, size)
    glyphs = []
    for code in codes:
        ch = chr(code)
        l, t, r, b = font.getbbox(ch, anchor='ls')
        w, h = max(r - l, 0), max(b - t, 0)
        bitmap = b''
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor='ls')
            bitmap = img.tobytes()
        glyphs.append((code, h, w, int(round(font.getlength(ch))), -t if h else 0, l, bitmap))
    ascent = max(g[4] for g in glyphs if g[1])
    descent = max(g[1] - g[4] for g in glyphs if g[1])
    data = struct.pack('>6i', len(glyphs), 11, size, 0, ascent, descent)
    for code, h, w, adv, dy, dx, _ in glyphs:
        assert 0 <= h < 256 and 0 <= w < 256 and -128 <= dx < 128, (code, h, w, dx)
        data += struct.pack('>7i', code, h, w, adv, dy, dx, 0)
    data += b''.join(g[6] for g in glyphs)
    rows = [f'  {", ".join("0x%02X" % x for x in data[i:i + 16])},' for i in range(0, len(data), 16)]
    (OUT / filename).write_text(
        '// Generated by tools/make_fonts.py from DejaVu Sans Bold (Bitstream Vera licence). Do not edit.\n'
        '#pragma once\n#include <Arduino.h>\n'
        f'const uint8_t {symbol}[] PROGMEM = {{\n' + '\n'.join(rows).rstrip(',') + '\n};\n')
    print(filename, len(glyphs), 'glyphs', len(data), 'bytes', 'ascent', ascent, 'descent', descent)

build(15, LATIN, 'Font15', 'Font15.h')
build(60, DIGITS, 'Font60', 'Font60.h')
